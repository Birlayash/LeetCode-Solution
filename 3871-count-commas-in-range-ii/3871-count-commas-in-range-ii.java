class Solution {
    public long countCommas(long n) {
        if(n<1000){
            return 0;
        }
        if(n<1000000){
            return n-999;
        }
        if(n<1000000000L){
            return 999000+(n-999999)*2;
        }
        if(n<1000000000000L){
            return 999000L+(999000000L )*2+(n-999999999L)*3;
        }
        if(n<1000000000000000L){
            return 999000L+(999000000L)*2+(999000000000L)*3+(n-999999999999L)*4;
        }
        return 999000L+ 999000000L * 2+ 999000000000L * 3+ 999000000000000L * 4+ (n - 999999999999999L) * 5;
    }
}